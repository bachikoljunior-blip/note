"""Protected-statistic deterministic replay certificate issuance gate.

Forward-only research candidate. A replay certificate is issued only when:
1) a predeclared structural exactness attestation is present,
2) fresh-process challenge pairs show zero protected-statistic mismatches, and
3) an anytime-valid Bernoulli upper bound on challenge-pair mismatch is below
   the configured tolerance using a lifetime alpha-spending schedule.

The statistical screen is NOT treated as proof of exact determinism. Structural
attestation is a separate mandatory authority input and is bound into the
certificate digest. A certificate generated by this module is suitable only for
a bootstrap registry that independently pins that exact certificate digest.
"""
from __future__ import annotations
from dataclasses import asdict, dataclass
from hashlib import sha256
import json, math
from typing import Any, Iterable, Sequence

SCHEMA_VERSION = 1
ALLOWED_PROTECTED_STATISTICS = frozenset({
    "raw_output","token_ids","score","paired_score_bits",
    "oriented_discordance_sign","custom_digest",
})
ALLOWED_PROOF_KINDS = frozenset({
    "content_addressed_pure_function",
    "verified_deterministic_runtime_contract",
})

class CertificateIssuanceError(RuntimeError):
    pass

def _canon(obj: Any) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",",":"), ensure_ascii=False).encode("utf-8")

def _digest(obj: Any) -> str:
    return sha256(_canon(obj)).hexdigest()

def _hex64(name: str, value: str) -> str:
    value=str(value)
    if len(value)!=64 or any(c not in "0123456789abcdef" for c in value):
        raise CertificateIssuanceError(f"{name} must be lowercase sha256 hex")
    return value

def _nonempty(name: str, value: str) -> str:
    value=str(value)
    if not value:
        raise CertificateIssuanceError(f"{name} must be nonempty")
    return value

@dataclass(frozen=True)
class RuntimeSnapshot:
    runtime_fingerprint_digest: str
    scorer_config_digest: str
    decoder_config_digest: str
    protected_statistic: str
    attempt_id_version: str
    def payload(self) -> dict[str, Any]:
        _hex64("runtime_fingerprint_digest", self.runtime_fingerprint_digest)
        _hex64("scorer_config_digest", self.scorer_config_digest)
        _hex64("decoder_config_digest", self.decoder_config_digest)
        if self.protected_statistic not in ALLOWED_PROTECTED_STATISTICS:
            raise CertificateIssuanceError("unsupported protected_statistic")
        _nonempty("attempt_id_version", self.attempt_id_version)
        return asdict(self)

@dataclass(frozen=True)
class StructuralAttestation:
    snapshot: RuntimeSnapshot
    proof_kind: str
    proof_artifact_digest: str
    proof_provenance_digest: str
    invalidation_conditions: tuple[str, ...]
    def payload(self) -> dict[str, Any]:
        if self.proof_kind not in ALLOWED_PROOF_KINDS:
            raise CertificateIssuanceError("unsupported structural proof kind")
        _hex64("proof_artifact_digest", self.proof_artifact_digest)
        _hex64("proof_provenance_digest", self.proof_provenance_digest)
        cond=tuple(str(x) for x in self.invalidation_conditions)
        if not cond or any(not x for x in cond) or len(set(cond))!=len(cond):
            raise CertificateIssuanceError("invalidation_conditions must be unique nonempty strings")
        return {
            "snapshot": self.snapshot.payload(),
            "proof_kind": self.proof_kind,
            "proof_artifact_digest": self.proof_artifact_digest,
            "proof_provenance_digest": self.proof_provenance_digest,
            "invalidation_conditions": list(cond),
        }
    @property
    def attestation_digest(self) -> str:
        return _digest(self.payload())

@dataclass(frozen=True)
class ChallengePair:
    challenge_id: str
    attempt_id: str
    fresh_process_id_a: str
    fresh_process_id_b: str
    protected_value_digest_a: str
    protected_value_digest_b: str
    def payload(self) -> dict[str, Any]:
        _nonempty("challenge_id", self.challenge_id); _nonempty("attempt_id", self.attempt_id)
        _nonempty("fresh_process_id_a", self.fresh_process_id_a); _nonempty("fresh_process_id_b", self.fresh_process_id_b)
        if self.fresh_process_id_a == self.fresh_process_id_b:
            raise CertificateIssuanceError("challenge pair must use distinct fresh processes")
        _hex64("protected_value_digest_a", self.protected_value_digest_a)
        _hex64("protected_value_digest_b", self.protected_value_digest_b)
        return asdict(self)
    @property
    def mismatch(self) -> int:
        self.payload()
        return int(self.protected_value_digest_a != self.protected_value_digest_b)

@dataclass(frozen=True)
class IssuancePolicy:
    lifetime_false_certification_budget: float
    certificate_generation_index: int
    mismatch_tolerance: float
    require_zero_observed_mismatch: bool = True
    def alpha_for_generation(self) -> float:
        A=float(self.lifetime_false_certification_budget)
        j=int(self.certificate_generation_index)
        if not (0 < A < 1): raise CertificateIssuanceError("lifetime budget must be in (0,1)")
        if j < 1: raise CertificateIssuanceError("generation index must be >=1")
        if not (0 < self.mismatch_tolerance < 1): raise CertificateIssuanceError("mismatch_tolerance must be in (0,1)")
        return A/(j*(j+1))
    def payload(self) -> dict[str, Any]:
        return {
            "lifetime_false_certification_budget": self.lifetime_false_certification_budget,
            "certificate_generation_index": self.certificate_generation_index,
            "generation_alpha": self.alpha_for_generation(),
            "mismatch_tolerance": self.mismatch_tolerance,
            "require_zero_observed_mismatch": bool(self.require_zero_observed_mismatch),
            "spending_rule": "A/[j(j+1)]",
        }

def _log_beta(x: float, y: float) -> float:
    return math.lgamma(x)+math.lgamma(y)-math.lgamma(x+y)

def _log_mixture_martingale(p: float,n:int,s:int,a:float=.5,b:float=.5)->float:
    if not (0 <= s <= n): raise ValueError("require 0<=s<=n")
    lm=_log_beta(s+a,n-s+b)-_log_beta(a,b)
    if p<=0: return math.inf if s else lm
    if p>=1: return math.inf if n-s else lm
    return lm - s*math.log(p) - (n-s)*math.log1p(-p)

def anytime_upper(n:int,s:int,alpha:float)->float:
    if n<=0: return 1.0
    if not (0 < alpha < 1): raise ValueError("alpha")
    target=math.log(1/alpha); phat=s/n; lo=max(phat,1e-15); hi=1-1e-15
    def f(p:float)->float: return _log_mixture_martingale(p,n,s)-target
    if f(hi)<0: return 1.0
    if f(lo)>0: return phat
    for _ in range(120):
        mid=(lo+hi)/2
        if f(mid)>0: hi=mid
        else: lo=mid
    return hi

def issue_certificate(
    *, certificate_id: str, snapshot: RuntimeSnapshot,
    structural_attestation: StructuralAttestation,
    challenge_pairs: Sequence[ChallengePair],
    policy: IssuancePolicy,
) -> dict[str, Any]:
    _nonempty("certificate_id", certificate_id)
    if structural_attestation.snapshot != snapshot:
        raise CertificateIssuanceError("structural attestation snapshot mismatch")
    snapshot_payload=snapshot.payload()
    att_payload=structural_attestation.payload()
    pairs=[p.payload() for p in challenge_pairs]
    if not pairs:
        raise CertificateIssuanceError("fresh-process challenge set is empty")
    challenge_ids=[p["challenge_id"] for p in pairs]
    attempt_ids=[p["attempt_id"] for p in pairs]
    if len(set(challenge_ids)) != len(challenge_ids):
        raise CertificateIssuanceError("duplicate challenge_id")
    if len(set(attempt_ids)) != len(attempt_ids):
        raise CertificateIssuanceError("each statistical trial must be a distinct attempt_id")
    # A process identifier may occur in only one trial. This prevents one output
    # from being silently reused across many pair comparisons.
    proc_ids=[x for p in pairs for x in (p["fresh_process_id_a"],p["fresh_process_id_b"])]
    if len(set(proc_ids)) != len(proc_ids):
        raise CertificateIssuanceError("fresh process identifiers are reused across challenge trials")
    mismatches=sum(int(p["protected_value_digest_a"] != p["protected_value_digest_b"]) for p in pairs)
    alpha=policy.alpha_for_generation()
    upper=anytime_upper(len(pairs), mismatches, alpha)
    status="certified"
    reason=None
    if policy.require_zero_observed_mismatch and mismatches:
        status="rejected"; reason="observed_protected_statistic_mismatch"
    elif upper > policy.mismatch_tolerance:
        status="rejected"; reason="insufficient_fresh_process_evidence"
    evidence_payload={
        "trial_unit_contract":"one distinct attempt_id, evaluated once in each of two distinct fresh process epochs",
        "trials":len(pairs),
        "mismatches":mismatches,
        "anytime_upper":upper,
        "alpha":alpha,
        "challenge_set_digest":_digest(pairs),
    }
    result={
        "schema_version":SCHEMA_VERSION,
        "status":status,
        "reason":reason,
        "certificate_id":certificate_id,
        "runtime_snapshot":snapshot_payload,
        "structural_attestation_digest":structural_attestation.attestation_digest,
        "structural_attestation":att_payload,
        "issuance_policy":policy.payload(),
        "fresh_process_evidence":evidence_payload,
        "certificate_digest":None,
        "certificate_payload":None,
        "validity_notes":[
            "Statistical fresh-process testing is a sanity screen, not proof of exact determinism.",
            "Replay eligibility additionally requires the structural attestation pinned by the bootstrap trust root.",
            "One statistical trial is one distinct attempt_id with two distinct fresh process epochs; all-pairs reuse is forbidden.",
            "Generation alpha follows a summable lifetime spending schedule and is never reset on recertification.",
        ],
    }
    if status=="certified":
        payload={
            "schema_version":SCHEMA_VERSION,
            "certificate_id":certificate_id,
            "runtime_snapshot":snapshot_payload,
            "structural_attestation_digest":structural_attestation.attestation_digest,
            "fresh_process_evidence_digest":_digest(evidence_payload),
            "issuance_policy_digest":_digest(policy.payload()),
            "invalidation_conditions":list(structural_attestation.invalidation_conditions),
        }
        result["certificate_payload"]=payload
        result["certificate_digest"]=_digest(payload)
    return result

